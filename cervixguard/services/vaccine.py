"""HPV vaccine registrations: dose scheduling, storage and calendar export."""
from datetime import datetime, timedelta

from ..db import connection

DOSE_NUMBERS = (1, 2, 3)


def compute_dose_schedule(age_at_dose1, dose1_date_str, immunocompromised=False):
    """Work out how many doses are needed and when each is due.

    age_at_dose1 is the age on the day of dose 1 (not today's age).
    Under 15 (and not immunocompromised) -> 2 doses: dose 2 = dose 1 + 180 days.
    15+ or immunocompromised -> 3 doses: dose 2 = dose 1 + 60 days,
    dose 3 = dose 2 + 120 days (180 days after dose 1).
    Raises ValueError for ages outside 9-45 or a bad date.
    """
    if age_at_dose1 < 9 or age_at_dose1 > 45:
        raise ValueError("HPV vaccine registration here is for ages 9 to 45.")

    dose1 = datetime.strptime(dose1_date_str, "%Y-%m-%d")

    if age_at_dose1 < 15 and not immunocompromised:
        doses_required = 2
        dose2 = dose1 + timedelta(days=180)   # 0, 6 month schedule
        dose3 = None
    else:
        doses_required = 3
        dose2 = dose1 + timedelta(days=60)    # 60 days after dose 1
        dose3 = dose2 + timedelta(days=120)   # 120 days after dose 2

    return {
        "doses_required": doses_required,
        "dose1_date": dose1.strftime("%Y-%m-%d"),
        "dose2_date": dose2.strftime("%Y-%m-%d"),
        "dose3_date": dose3.strftime("%Y-%m-%d") if dose3 else None,
    }


def list_registrations(user_id):
    with connection() as conn:
        return [dict(r) for r in conn.execute(
            "SELECT * FROM vaccine_registrations WHERE user_id = ? ORDER BY dose1_date ASC",
            (user_id,),
        )]


def get_registration(reg_id, user_id):
    with connection() as conn:
        row = conn.execute(
            "SELECT * FROM vaccine_registrations WHERE id = ? AND user_id = ?", (reg_id, user_id)
        ).fetchone()
    return dict(row) if row else None


def create_registration(user_id, patient_name, age, schedule, immunocompromised=False):
    with connection() as conn:
        conn.execute("""
            INSERT INTO vaccine_registrations
                (user_id, patient_name, age, doses_required, dose1_date, dose2_date, dose3_date,
                 immunocompromised, created_at)
            VALUES (?,?,?,?,?,?,?,?,?)
        """, (
            user_id, patient_name, age, schedule["doses_required"],
            schedule["dose1_date"], schedule["dose2_date"], schedule["dose3_date"],
            1 if immunocompromised else 0,
            datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        ))


def mark_dose_done(reg_id, dose_num, user_id):
    if dose_num not in DOSE_NUMBERS:
        return
    with connection() as conn:
        conn.execute(
            f"UPDATE vaccine_registrations SET dose{dose_num}_done = 1 WHERE id = ? AND user_id = ?",
            (reg_id, user_id),
        )


def delete_registration(reg_id, user_id):
    with connection() as conn:
        conn.execute(
            "DELETE FROM vaccine_registrations WHERE id = ? AND user_id = ?", (reg_id, user_id)
        )


def build_ics(registration, dose_num):
    """iCalendar text for one dose's due date, or None if that dose isn't scheduled."""
    dose_date = registration.get(f"dose{dose_num}_date")
    if not dose_date:
        return None
    return "\r\n".join([
        "BEGIN:VCALENDAR",
        "VERSION:2.0",
        "PRODID:-//CervixGuard AI//Vaccine//EN",
        "BEGIN:VEVENT",
        f"UID:cervixguard-vax-{registration['id']}-dose{dose_num}@local",
        f"DTSTAMP:{datetime.utcnow().strftime('%Y%m%dT%H%M%SZ')}",
        f"DTSTART;VALUE=DATE:{dose_date.replace('-', '')}",
        f"SUMMARY:CervixGuard AI — HPV Vaccine Dose {dose_num} ({registration['patient_name']})",
        "DESCRIPTION:HPV vaccination reminder generated by CervixGuard AI.",
        "END:VEVENT",
        "END:VCALENDAR",
        "",
    ])